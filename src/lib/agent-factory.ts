export const FACTORY_LIST = Object.values(FACTORY_TYPES);

/** 关键词识别：从名字/目标/行动/检查里判断属于哪一类 */
export function detectFactoryType(...texts: string[]): FactoryTypeId {
  const t = texts.join(" ");
  let best: FactoryTypeId = "custom";
  let bestHit = 0;
  for (const type of FACTORY_LIST) {
    let hit = 0;
    for (const k of type.keywords) if (t.includes(k)) hit++;
    if (hit > bestHit) {
      bestHit = hit;
      best = type.id;
    }
  }
  return best;
}

