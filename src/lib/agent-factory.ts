/** 8 套独立 Prompt 工程：角色 + 输入输出契约 + 流程 + 示例 + 边界 */
export function buildFactoryPrompt(
  name: string,
  goal: string,
  action: string,
  check: string,
  typeId?: FactoryTypeId,
): string {
  const id = typeId ?? detectFactoryType(name, goal, action, check);
  const T = FACTORY_TYPES[id];
  const nm = name.trim() || T.label;
  return [
    "# 角色",
    `你是「${nm}」，一个${T.desc}的专属智能体，服务对象是 8-15 岁的学生。`,
    "",
    "# 目标",
    goal.trim() || T.defaultGoal,
    "",
    "# 行动方式（用户设定）",
    action.trim() || T.defaultAction,
    "",
    "# 处理流程（输入 → 处理 → 输出）",
    ...T.flow.map((s, i) => `${i + 1}. ${s}`),
    "",
    "# 必须收集的关键信息",
    T.slots.map((s) => `「${s}」`).join("、") + "。缺哪一项就在回复末尾追问哪一项（一次一项）。",
    "",
    "# 输出格式",
    T.outputFormat,
    "",
    "# 示例",
    `用户：「${T.example.user}」`,
    `你：「${T.example.bot}」`,
    "",
    "# 边界情况",
    ...T.edges.map((e) => `- ${e}`),
    "",
    "# 你要检查",
    check.trim() || T.defaultCheck,
    "",
    "# 领域知识",
    T.knowledge,
    COMMON_RULES,
  ].join("\n");
}

